package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

func main() {
	file, err := parser.ParseFile(token.NewFileSet(), "internal/pgproto/pg_query.pb.go", nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by internal/cmd/genapi; DO NOT EDIT.\n\npackage pg_query\n\nimport pgproto \"github.com/gosuda/pg18_query_go/internal/pgproto\"\n\n")
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			switch spec := spec.(type) {
			case *ast.TypeSpec:
				if ast.IsExported(spec.Name.Name) {
					fmt.Fprintf(&out, "type %s = pgproto.%s\n", spec.Name, spec.Name)
				}
			case *ast.ValueSpec:
				for _, name := range spec.Names {
					if ast.IsExported(name.Name) {
						fmt.Fprintf(&out, "%s %s = pgproto.%s\n", gen.Tok, name, name)
					}
				}
			}
		}
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("types.go", source, 0644); err != nil {
		log.Fatal(err)
	}
}
